package org.demo.documentation.widgets.tree.base.any;

import lombok.RequiredArgsConstructor;
import org.cxbox.core.controller.param.QueryParameters;
import org.cxbox.core.crudma.bc.BusinessComponent;
import org.cxbox.core.dao.impl.AbstractAnySourceBaseDAO;
import org.cxbox.core.exception.BusinessException;
import org.demo.documentation.widgets.tree.data.departments.DepartmentUsersPrj;
import org.demo.documentation.widgets.tree.data.departments.Mydepartments;
import org.demo.documentation.widgets.tree.data.departments.MydepartmensRepository;
import org.demo.documentation.widgets.tree.data.users.My3261Users;
import org.demo.documentation.widgets.tree.data.users.Myusers361Repository;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageImpl;
import org.springframework.data.domain.PageRequest;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.Objects;
import java.util.stream.Stream;

@Service
@RequiredArgsConstructor
public class Myexample3261AnyDAO extends AbstractAnySourceBaseDAO<Myexample3261AnyDTO> {

	private final MydepartmensRepository repository;

	private final Myusers361Repository userRepository;
	private static final int DEFAULT_PAGE = 1;
	private static final int DEFAULT_LIMIT = 20;

	@Override
	public String getId(Myexample3261AnyDTO entity) {
		return entity.getId();
	}

	@Override
	public void setId(String id, Myexample3261AnyDTO entity) {
		entity.setId(id);
	}

	@Override
	public Myexample3261AnyDTO getByIdIgnoringFirstLevelCache(BusinessComponent bc) {
		String id = bc.getId();
		if (id == null || !id.contains("-") || isNew(id)) {
			return null;
		}

		String departmentId = extractDepartmentId(id);
		return getData(bc, departmentId).stream()
				.filter(dto -> Objects.equals(dto.getId(), id))
				.findFirst()
				.orElse(null);
	}

	@Override
	public Page<Myexample3261AnyDTO> getList(BusinessComponent bc, QueryParameters queryParameters) {
		// a node has few rows: they are read at once, so the page knows the total count (More in the tree, /count)
		PaginationParams pagination = extractPaginationParams(bc);
		List<Myexample3261AnyDTO> all = getData(new PaginationParams(0, Integer.MAX_VALUE), extractFilterParams(bc), null).stream()
				.map(this::toDTO)
				.toList();
		int from = Math.min(pagination.offset(), all.size());
		int to = Math.min(from + pagination.limit(), all.size());
		return new PageImpl<>(all.subList(from, to), PageRequest.of(pagination.offset() / pagination.limit(), pagination.limit()), all.size());
	}

	/**
	 * A row is a pair "department-user" (user 0 for a department without users).
	 * A new row is a new department, with its first user when a name of the user is filled.
	 */
	@Override
	@Transactional
	public Myexample3261AnyDTO create(BusinessComponent bc, Myexample3261AnyDTO entity) {
		Mydepartments department = repository.save(new Mydepartments()
				.setDepartmentName(entity.getDepartment())
				.setParentId(entity.getParentId() == null ? null : departmentId(entity.getParentId())));
		long userId = 0L;
		if (hasUserName(entity)) {
			My3261Users user = userRepository.save(new My3261Users());
			setUserName(user, entity);
			department.getFullNameList().add(user);
			userId = user.getId();
		}
		return getRow(department.getId(), userId);
	}

	/**
	 * The department name is changed for all users of the department, the user name only for this row.
	 */
	@Override
	@Transactional
	public Myexample3261AnyDTO update(BusinessComponent bc, Myexample3261AnyDTO entity) {
		Long departmentId = departmentId(entity.getId());
		Long userId = userId(entity.getId());
		repository.findById(departmentId).orElseThrow().setDepartmentName(entity.getDepartment());
		if (userId != 0L) {
			setUserName(userRepository.findById(userId).orElseThrow(), entity);
		}
		return getRow(departmentId, userId);
	}

	/**
	 * A row with a user removes the user from the department, a row without users removes the department.
	 */
	@Override
	@Transactional
	public void delete(BusinessComponent bc) {
		Long departmentId = departmentId(bc.getId());
		Long userId = userId(bc.getId());
		Mydepartments department = repository.findById(departmentId).orElseThrow();
		if (userId != 0L) {
			department.getFullNameList().removeIf(user -> Objects.equals(user.getId(), userId));
			return;
		}
		if (repository.existsByParentId(departmentId)) {
			throw new BusinessException().addPopup("The department has nested departments. Delete them first.");
		}
		repository.delete(department);
	}

	/** The new row has not been saved yet: its id is generated by the framework. */
	public static boolean isNew(String id) {
		return id != null && id.startsWith("-");
	}

	/** The user part of the row id, 0 for a department without users. */
	public static boolean hasUser(String id) {
		return id != null && !isNew(id) && userId(id) != 0L;
	}

	private Myexample3261AnyDTO getRow(Long departmentId, Long userId) {
		String id = departmentId + "-" + userId;
		return repository.allDepartmentUsersDeptId(0, Integer.MAX_VALUE, String.valueOf(departmentId)).stream()
				.map(this::toDTO)
				.filter(dto -> Objects.equals(dto.getId(), id))
				.findFirst()
				.orElseThrow();
	}

	private static boolean hasUserName(Myexample3261AnyDTO entity) {
		return Stream.of(entity.getLastName(), entity.getFirstName(), entity.getMiddleName())
				.anyMatch(name -> name != null && !name.isBlank());
	}

	private static void setUserName(My3261Users user, Myexample3261AnyDTO entity) {
		user.setLastName(entity.getLastName())
				.setFirstName(entity.getFirstName())
				.setMiddleName(entity.getMiddleName());
	}

	private static Long departmentId(String compositeId) {
		return Long.valueOf(compositeId.split("-")[0]);
	}

	private static Long userId(String compositeId) {
		return Long.valueOf(compositeId.split("-")[1]);
	}

	public List<Myexample3261AnyDTO> getData(BusinessComponent bc, String deptId) {
		PaginationParams pagination = extractPaginationParams(bc);
		FilterParams filters = extractFilterParams(bc);

		List<DepartmentUsersPrj> entities = getData(pagination, filters, deptId);

		return entities.stream()
				.map(this::toDTO)
				.toList();
	}



	private PaginationParams extractPaginationParams(BusinessComponent bc) {
		String pageStr = bc.getParameters().getParameter("_page");
		String limitStr = bc.getParameters().getParameter("_limit");

		int page = parseOrDefault(pageStr, DEFAULT_PAGE);
		int limit = Math.max(1, parseOrDefault(limitStr, DEFAULT_LIMIT));
		int offset = (page - 1) * limit;

		return new PaginationParams(offset, limit);
	}

	private FilterParams extractFilterParams(BusinessComponent bc) {
		String isLeafParam = bc.getParameters().getParameter("parentId.specified");
		String parentIdParam = bc.getParameters().getParameter("parentId.equals");

		return new FilterParams(
				isLeafParam != null ? Boolean.parseBoolean(isLeafParam) : null,
				parentIdParam
		);
	}

	private List<DepartmentUsersPrj> getData(PaginationParams pagination,
	                                         FilterParams filters,
	                                         String deptId) {
		int offset = pagination.offset();
		int limit = pagination.limit();


		if (deptId != null) {
			return repository.allDepartmentUsersDeptId(offset, limit, deptId);
		}

		if (filters.isLeaf() != null) {
			return repository.allDepartmentUsersisLeaf(offset, limit, filters.isLeaf());
		}

		if (filters.parentId() != null && !filters.parentId().isEmpty()) {
			String parentIdExtract = extractDepartmentId(filters.parentId());
			return	repository.allDepartmentUsersParentId(offset, limit,parentIdExtract);
		}

		return repository.allDepartmentUsers(offset, limit);
	}

	private Myexample3261AnyDTO toDTO(DepartmentUsersPrj entity) {
		Myexample3261AnyDTO myexample3261AnyDTO = new Myexample3261AnyDTO()
				.setDepartment(entity.departmentName())
				.setParentId(entity.parentId())
				.setIsLeaf(entity.isLeaf())
				.setLastName(entity.lastName())
				.setFullName(entity.fullName())
				.setFirstName(entity.firstName())
				.setMiddleName(entity.middleName());
		myexample3261AnyDTO.setId(entity.id());
		return myexample3261AnyDTO;
	}

	private int parseOrDefault(String value, int defaultValue) {
		if (value == null || value.isBlank()) {
			return defaultValue;
		}
		try {
			return Integer.parseInt(value.trim());
		} catch (NumberFormatException e) {
			return defaultValue;
		}
	}

	private String extractDepartmentId(String compositeId) {
		if (compositeId == null || !compositeId.contains("-")) {
			return compositeId;
		}
		return compositeId.split("-")[0];
	}

	private record PaginationParams(int offset, int limit) {}

	private record FilterParams(Boolean isLeaf, String parentId) {}
}